async function main() {
  console.log("开始创建种子数据...");

  for (const materialData of seedData) {
    const { questions, ...materialInfo } = materialData;

    const material = await prisma.material.create({
      data: {
        title: materialInfo.title,
        content: materialInfo.content,
        tableData: materialInfo.tableData,
        category: materialInfo.category,
        difficulty: materialInfo.difficulty,
      },
    });

    for (let i = 0; i < questions.length; i++) {
      const question = questions[i];
      await prisma.question.create({
        data: {
          materialId: material.id,
          questionText: question.questionText,
          options: question.options,
          correctAnswer: question.correctAnswer,
          skillType: question.skillType,
          explanation: question.explanation,
          formula: question.formula,
          calculation: question.calculation,
          tip: question.tip,
          orderIndex: i,
        },
      });
    }

    console.log(`已创建材料：${material.title}`);
  }

  console.log("种子数据创建完成！");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
